import numpy as np
import hashlib
import matplotlib.pyplot as plt

from qiskit import QuantumCircuit, transpile
from qiskit.primitives import StatevectorSampler

USE_HARDWARE = False   # Flip to True when ready for real IBM hardware

SHOTS = 1024           # How many times each circuit runs

# Optimal measurement angles for CHSH (in radians)
ANGLES = {
    'A0':  np.pi / 2,
    'A1':  0.0,
    'B0':  np.pi / 4,
    'B1': -np.pi / 4,
}

# The 4 combinations and their signs in S = E(A0,B0) - E(A0,B1) + E(A1,B0) + E(A1,B1)
SIGNS = {
    ('A0', 'B0'): +1,
    ('A0', 'B1'): -1,
    ('A1', 'B0'): +1,
    ('A1', 'B1'): +1,
}

# HOW THIS WORKS:
# Step 1: H gate puts qubit 0 into superposition (50% |0>, 50% |1>)
# Step 2: CNOT (CX) gate entangles qubit 1 with qubit 0
# Result: the two qubits are now in a Bell state — they are correlated
#         in a way that is impossible to explain classically.
# Step 3: RY rotations let us measure in different "directions" (bases).

def build_circuit(alice_angle, bob_angle):
    qc = QuantumCircuit(2)

    # Create Bell state
    qc.h(0)       # Hadamard: superposition
    qc.cx(0, 1)   # CNOT: entangle

    # Rotate to measurement basis
    qc.ry(-alice_angle, 0)
    qc.ry(-bob_angle,   1)

    qc.measure_all()
    return qc

# Draw an example circuit to see what it looks like
print("Example circuit (settings A0, B0):")
print(build_circuit(ANGLES['A0'], ANGLES['B0']).draw('text'))

# HOW THIS WORKS:
# After running SHOTS times, we get counts like {'00': 510, '11': 490, '01': 12, '10': 12}
# '00' and '11' = Alice and Bob AGREED  → contribute +1
# '01' and '10' = Alice and Bob DISAGREED → contribute -1
# E = (agreements - disagreements) / total shots
#
# Then S = E(A0,B0) - E(A0,B1) + E(A1,B0) + E(A1,B1)
# Classical physics says |S| <= 2
# Quantum mechanics allows |S| up to 2√2 ≈ 2.828

def expectation_value(counts):
    total      = sum(counts.values())
    n_agree    = counts.get('00', 0) + counts.get('11', 0)
    n_disagree = counts.get('01', 0) + counts.get('10', 0)
    return (n_agree - n_disagree) / total


def compute_S_and_error(sampler, circuits_and_settings):
    E_values   = {}
    E_errors   = {}
    all_counts = {}

    for qc, alice_key, bob_key in circuits_and_settings:
        label  = f"{alice_key}{bob_key}"
        result = sampler.run([qc], shots=SHOTS).result()
        counts = result[0].data.meas.get_counts()

        all_counts[label] = counts
        E = expectation_value(counts)
        E_values[label]   = E
        E_errors[label]   = np.sqrt((1 - E**2) / SHOTS)

        print(f"  E({alice_key},{bob_key}) = {E:+.4f}  ±{E_errors[label]:.4f}  counts: {counts}")

    # S = sum of signed E values
    S = sum(sign * E_values[f"{a}{b}"] for (a, b), sign in SIGNS.items())

    # Error on S = sqrt(sum of squared errors) — independent measurements
    sigma_S = np.sqrt(sum(e**2 for e in E_errors.values()))

    return S, sigma_S, E_values, all_counts

# HOW THIS WORKS:
# The honest player uses the real Bell circuit (entangled qubits).
# Their S value will be close to 2√2 ≈ 2.828 — well above the classical bound of 2.
# They also publish a hash of their winner bits as a "commitment" —
# proof that they didn't change the bits after seeing results.

def hash_bits(bitstring):
    return hashlib.sha256(bitstring.encode()).hexdigest()


def extract_winner_bits(all_counts):
    bits = ""
    for label in ['A0B0', 'A0B1', 'A1B0', 'A1B1']:
        most_common = max(all_counts[label], key=all_counts[label].get)
        bits += most_common   # 2 bits per setting → 8 bits total
    return bits


def run_honest_player(name, sampler):
    print(f"\n{'='*50}")
    print(f"  HONEST PLAYER: {name}")
    print(f"{'='*50}")

    circuits_and_settings = [
        (build_circuit(ANGLES[a], ANGLES[b]), a, b)
        for (a, b) in SIGNS.keys()
    ]

    S, sigma_S, E_values, all_counts = compute_S_and_error(sampler, circuits_and_settings)

    winner_bits = extract_winner_bits(all_counts)
    commitment  = hash_bits(winner_bits)

    print(f"\n  S = {S:.4f}  ±{sigma_S:.4f}  (classical bound = 2.000, quantum max = {2*np.sqrt(2):.4f})")
    print(f"  Winner bits: {winner_bits}")
    print(f"  Commitment:  {commitment[:16]}...")

    return {
        'name': name, 'is_cheater': False,
        'S': S, 'sigma_S': sigma_S,
        'E_values': E_values,
        'winner_bits': winner_bits,
        'commitment': commitment,
        'all_counts': all_counts,
    }

# HOW THIS WORKS:
# The cheater removes the H gate and CNOT gate — no entanglement!
# Their qubits are independent and classically correlated.
# Without entanglement, |S| <= 2 — they can't beat the classical bound.
# The verifier catches this in Cell 8.

def build_rigged_circuit(alice_angle, bob_angle):
    qc = QuantumCircuit(2)
    # NO qc.h(0)    ← missing Hadamard
    # NO qc.cx(0,1) ← missing CNOT (no entanglement)
    qc.ry(-alice_angle, 0)
    qc.ry(-bob_angle,   1)
    qc.measure_all()
    return qc


def run_cheater(name, sampler):
    print(f"\n{'='*50}")
    print(f"  CHEATER: {name}  (skipping entanglement secretly)")
    print(f"{'='*50}")

    circuits_and_settings = [
        (build_rigged_circuit(ANGLES[a], ANGLES[b]), a, b)
        for (a, b) in SIGNS.keys()
    ]

    S, sigma_S, E_values, all_counts = compute_S_and_error(sampler, circuits_and_settings)

    winner_bits = extract_winner_bits(all_counts)
    commitment  = hash_bits(winner_bits)

    print(f"\n  S = {S:.4f}  ±{sigma_S:.4f}  (should be <= 2.000 — caught!)")
    print(f"  Winner bits: {winner_bits}")
    print(f"  Commitment:  {commitment[:16]}...")

    return {
        'name': name, 'is_cheater': True,
        'S': S, 'sigma_S': sigma_S,
        'E_values': E_values,
        'winner_bits': winner_bits,
        'commitment': commitment,
        'all_counts': all_counts,
    }

sampler = StatevectorSampler()

alice   = run_honest_player("Alice",   sampler)
bob     = run_honest_player("Bob",     sampler)
mallory = run_cheater(       "Mallory", sampler)

players = [alice, bob, mallory]
print("\n\nAll players finished!")

# HOW THIS WORKS:
# We flag anyone whose S does NOT beat 2 by at least 5 standard deviations.
# 5 sigma = less than 1-in-3.5-million chance of a false accusation.
# We also verify the commitment hash to confirm bits weren't changed.

SIGMA_THRESHOLD = 5.0

def verify_player(player):
    S, sigma_S = player['S'], player['sigma_S']
    sigmas_above  = (S - 2.0) / sigma_S
    passes_bell   = sigmas_above >= SIGMA_THRESHOLD
    hash_matches  = hashlib.sha256(player['winner_bits'].encode()).hexdigest() == player['commitment']
    passes        = passes_bell and hash_matches

    print(f"\n  Player: {player['name']}")
    print(f"    S = {S:.4f},  {sigmas_above:.1f}σ above classical bound  (need >= {SIGMA_THRESHOLD}σ)")
    print(f"    Bell test:  {'PASS ✓' if passes_bell  else 'FAIL ✗'}")
    print(f"    Hash check: {'PASS ✓' if hash_matches else 'FAIL ✗'}")
    print(f"    --> {'VERIFIED HONEST ✓' if passes else 'FLAGGED AS CHEATER ✗'}")

    return passes

print("=" * 50)
